"""V9 custom amino-acid / protected building-block catalog, bounded local import.

User-supplied SMILES are structural assertions to REVIEW, not vendor verification.
No sequence mass is inferred from a short name or an approximate group delta.
"""
from __future__ import annotations

import csv
import hashlib
import math
import json
import re
from pathlib import Path
from typing import Any

from .atomic_topology_v9 import _read_monomer, TopologyError
from .strict_json_v9 import loads_scientific_json

_TOKEN = re.compile(r'^[A-Za-z][A-Za-z0-9_+.-]{0,39}$')
MAX_CATALOG_FILE=2_000_000
MAX_CATALOG_RECORDS=512


def verify_monomer_entry(row: dict[str,Any]) -> dict[str,Any]:
    """Verify atom maps and, if supplied, a *neutral average* vendor MW.

    The reported mass must describe the exact structure, without counterions
    or solvents. Different salts/solvates require distinct structural review.
    Nothing is automatically registered based on a vendor number alone.
    """
    from rdkit.Chem import Descriptors, rdMolDescriptors
    if not isinstance(row,dict):
        raise TopologyError('Monomer entry must be an object.')
    accepted = {'token', 'smiles', 'source', 'reported_mw', 'mw', 'name',
                # Derived fields generated by this function may be revalidated.
                'formula', 'average_neutral_monomer_mw', 'exact_neutral_monomer_mass',
                'reported_mw_delta', 'validation'}
    extra=set(row)-accepted
    if extra:
        raise TopologyError(f'Unknown monomer columns {sorted(map(str,extra))!r}. Use token, smiles, source, reported_mw.')
    token=row.get('token')
    if not isinstance(token,str) or not _TOKEN.fullmatch(token):
        raise TopologyError('Monomer token must be an ASCII identifier 1–40 characters.')
    smiles=row.get('smiles')
    mol=_read_monomer({'smiles':smiles},1)
    average=float(Descriptors.MolWt(mol))
    reported_candidates=[row[k] for k in ('reported_mw','mw') if row.get(k) not in (None,'')]
    reported=None
    if reported_candidates:
        try:
            numeric=[float(value) for value in reported_candidates]
        except (ValueError, TypeError, OverflowError) as exc:
            raise TopologyError('Reported monomer MW must be numeric g/mol.') from exc
        if any(not math.isfinite(x) or x<=0 for x in numeric):
            raise TopologyError('Reported monomer MW must be finite and positive.')
        if any(abs(x-numeric[0])>1e-9 for x in numeric[1:]):
            raise TopologyError('Conflicting reported_mw and mw columns.')
        reported=numeric[0]
        if abs(reported-average)>0.25:
            raise TopologyError(f'Reported neutral MW {reported:.4f} disagrees with atom-mapped structure '
                                f'{average:.4f} g/mol. Check protecting groups, counterions and solvates.')
    evidence=str(row.get('source','')).strip()[:240]
    result={'token':token,'smiles':smiles.strip(),
            'formula':rdMolDescriptors.CalcMolFormula(mol),
            'average_neutral_monomer_mw':round(average,5),
            'exact_neutral_monomer_mass':round(rdMolDescriptors.CalcExactMolWt(mol),6),
            'source':evidence,'validation':'ATOM_MAPPED_ONLY_OPERATOR_REVIEW_REQUIRED'}
    if reported is not None:
        result['reported_mw']=reported
        result['reported_mw_delta']=round(reported-average,5)
    return result


def _parse_input(path:Path, *, sheet: str|None):
    suffix=path.suffix.lower()
    if suffix=='.json':
        data=loads_scientific_json(path.read_text(encoding='utf-8'),max_bytes=MAX_CATALOG_FILE)
        rows=data.get('monomers') if isinstance(data,dict) else data
        if not isinstance(rows,list):raise TopologyError('JSON catalog must contain a monomers array.')
        return rows
    if suffix in ('.csv','.tsv'):
        with path.open('r',encoding='utf-8-sig',newline='') as stream:
            reader=csv.DictReader(stream,delimiter='\t' if suffix=='.tsv' else ',')
            columns=[str(key or '').strip().lower() for key in (reader.fieldnames or [])]
            if (not {'token','smiles'} <= set(columns) or len(set(columns))!=len(columns)
                    or '' in columns or len(columns)>64):
                raise TopologyError('CSV/TSV requires unique token and smiles headers (maximum 64 columns).')
            rows=[]
            for line,row in enumerate(reader,2):
                if line>MAX_CATALOG_RECORDS+1:
                    raise TopologyError('Catalog exceeds row limit.')
                if None in row or any(len(str(x))>4000 for x in row.values() if x is not None):
                    raise TopologyError(f'Invalid or excessively long catalog row {line}.')
                if not any(x and str(x).strip() for x in row.values()):
                    continue
                rows.append({k.strip().lower():v for k,v in row.items()})
            return rows
    if suffix=='.xlsx':
        from openpyxl import load_workbook
        wb=load_workbook(path,read_only=True,data_only=True)
        try:
            ws=wb[sheet] if sheet else wb.active
            iterator=ws.iter_rows(values_only=True)
            header=next(iterator,None)
            if not header:raise TopologyError('Excel header missing.')
            keys=[str(x).strip().lower() if x is not None else '' for x in header]
            if ('token' not in keys or 'smiles' not in keys or '' in keys
                    or len(set(keys)) != len(keys) or len(keys)>64):
                raise TopologyError('Excel requires unique token and smiles columns (maximum 64 columns).')
            rows=[]
            for i,values in enumerate(iterator):
                if i>=MAX_CATALOG_RECORDS:raise TopologyError('Catalog exceeds row limit.')
                if len(values)>64 or any(len(str(x))>4000 for x in values if x is not None):
                    raise TopologyError('Excessively wide or long Excel row.')
                if not any(x is not None for x in values):continue
                rows.append({key:value for key,value in zip(keys,values) if key})
            return rows
        finally:wb.close()
    raise TopologyError('Only .json, .xlsx, .csv, and .tsv catalogs are accepted.')


def import_monomer_catalog(file, *, sheet=None):
    """Inspect monomers locally; never silently register or overwrite entries."""
    p=Path(file)
    if p.is_symlink() or not p.is_file() or p.stat().st_size>MAX_CATALOG_FILE:
        raise TopologyError('Missing catalog or file larger than 2 MB.')
    rows=_parse_input(p,sheet=sheet)
    if len(rows)>MAX_CATALOG_RECORDS:
        raise TopologyError('Catalog exceeds 512 records.')
    seen=set();validated=[];rejected=[]
    for idx,row in enumerate(rows,2):
        try:
            if not isinstance(row,dict):raise TopologyError('Expected a table row.')
            row={str(k).strip().lower():v for k,v in row.items()}
            item=verify_monomer_entry(row)
            norm=item['token'].casefold()
            if norm in seen:raise TopologyError('Duplicate token (case insensitive).')
            seen.add(norm);validated.append(item)
        except (ValueError,TypeError,KeyError) as exc:
            rejected.append({'row':idx,'reason':str(exc)[:200]})
    return {'status':'REVIEW_REQUIRED_NO_AUTO_APPLICATION','accepted_count':len(validated),
            'rejected_count':len(rejected),'accepted':validated,'rejected':rejected,
            'file_sha256':hashlib.sha256(p.read_bytes()).hexdigest(),
            'notice':'Input structures supplied by operator; vendor identity and stereochemistry are NOT established.'}


def resolve_catalog_tokens(payload, catalog: dict):
    """Resolve registered names without silently substituting another structure.

    Atom maps, stereochemistry and protecting-group connectivity are part of
    the identity. If both token and SMILES are supplied they must agree.
    """
    if not isinstance(payload,dict):raise TopologyError('Expected topology object.')
    if not isinstance(catalog,dict):raise TopologyError('Expected a token lookup.')
    from rdkit import Chem
    import copy
    result=copy.deepcopy(payload)
    monomer_lists=([result['monomers']] if result.get('chains') is None else
                   [c['monomers'] for c in result['chains']])
    for monomers in monomer_lists:
        for monomer in monomers:
            if not isinstance(monomer,dict):raise TopologyError('Invalid monomer entry.')
            if 'token' not in monomer:
                continue
            token=monomer['token']
            if not isinstance(token,str):
                raise TopologyError('Monomer token must be text.')
            item=catalog.get(token)
            if item is None:raise TopologyError(f'Unregistered monomer: {token!r}')
            if item.get('validation')!='ATOM_MAPPED_ONLY_OPERATOR_REVIEW_REQUIRED':
                raise TopologyError('Catalog item is not a structurally validated record.')
            if item.get('token') != token:
                raise TopologyError('Catalog token does not match its registry key.')
            verified=verify_monomer_entry(item)
            registered=verified['smiles']
            if 'smiles' in monomer:
                # Compare stereochemical structures INCLUDING atom maps so that
                # alpha termini or a branch site cannot be silently remapped.
                provided=_read_monomer({'smiles':monomer['smiles']},1)
                reference=_read_monomer({'smiles':registered},1)
                from rdkit import Chem
                # _read_monomer clears map numbers; compare each ref property
                # after canonicalization by temporarily restoring the map labels.
                def canonical(mol):
                    clone=Chem.Mol(mol)
                    for atom in clone.GetAtoms():
                        if atom.HasProp('_spps_ref'):
                            atom.SetAtomMapNum(int(atom.GetProp('_spps_ref').split(':')[1]))
                    return Chem.MolToSmiles(clone,isomericSmiles=True,canonical=True)
                if canonical(provided)!=canonical(reference):
                    raise TopologyError(f'Monomer {token!r}: supplied SMILES disagrees with registered chemistry.')
            monomer['smiles']=registered
    return result
